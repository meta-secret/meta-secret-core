import { test } from 'node:test';
import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import { waitForCanonicalTerminal, bindWebFailureGuard, browserOwnedSecretUsable } from './web-postcondition.mjs';

function fakeStore() {
  const listeners = new Set();
  const store = { isSynchronizing: true, syncError: '', states: [],
    currState: { as_vault: () => ({ as_member: () => ({ deletion_states_json: () => JSON.stringify(store.states) }) }) },
    $subscribe: (callback) => { listeners.add(callback); return () => listeners.delete(callback); },
    emit: () => { for (const callback of listeners) callback(); }, listeners,
  }; return store;
}

test('terminal metadata is not accepted while the synchronization overlay hides the row', async () => {
  const store = fakeStore(); let completed = false;
  const result = waitForCanonicalTerminal({ passId: 'exact-id', requestId: 'exact-uuid', expectedStatus: 'Done', store }).then((value) => { completed = true; return value; });
  store.states = [{ secretId: 'exact-id', requestId: 'exact-uuid', clientStatus: 'Done' }]; store.emit();
  await Promise.resolve(); assert.equal(completed, false);
  store.isSynchronizing = false; store.emit();
  assert.equal((await result).requestId, 'exact-uuid'); assert.equal(store.listeners.size, 0);
});

test('foreign IDs/UUIDs cannot satisfy a terminal barrier; actual contradictions fail immediately', async () => {
  const store = fakeStore(); store.isSynchronizing = false;
  const result = waitForCanonicalTerminal({ passId: 'exact-id', requestId: 'exact-uuid', expectedStatus: 'Done', store });
  store.states = [{ secretId: 'foreign-id', requestId: 'exact-uuid', clientStatus: 'Done' }, { secretId: 'exact-id', requestId: 'foreign-uuid', clientStatus: 'Done' }]; store.emit();
  assert.equal(store.listeners.size, 1);
  store.states.push({ secretId: 'exact-id', requestId: 'exact-uuid', clientStatus: 'Declined' }); store.emit();
  await assert.rejects(result, /contradicts/); assert.equal(store.listeners.size, 0);
});

test('sync failures reject the barrier without issuing a synchronization request', async () => {
  const store = fakeStore(); store.isSynchronizing = false; store.syncError = 'failure';
  await assert.rejects(waitForCanonicalTerminal({ passId: 'id', expectedStatus: 'Done', store }), /synchronization failed/);
  assert.equal(store.listeners.size, 0);
});

test('page errors/null Rust pointers and renderer crashes reject business immediately and listeners detach', () => {
  const page = new EventEmitter(); const errors = [];
  const detach = bindWebFailureGuard(page, (error) => errors.push(error));
  page.emit('console', { type: () => 'warn', text: () => 'normal warning' }); assert.equal(errors.length, 0);
  page.emit('console', { type: () => 'error', text: () => 'null pointer passed to rust' });
  page.emit('pageerror', new Error('payload must not appear')); page.emit('crash');
  assert.equal(errors.length, 3); assert(errors.every((error) => !error.message.includes('payload')));
  detach(); assert.equal(page.listenerCount('pageerror'), 0); assert.equal(page.listenerCount('console'), 0);
});

test('the exact browser-owned Secret must remain readable after the awaited operation', () => {
  const owned = { __wbg_ptr: 23, get name() { if (!this.__wbg_ptr) throw new Error('consumed'); return 'label'; }, id_str() { if (!this.__wbg_ptr) throw new Error('consumed'); return 'opaque-id'; } };
  assert.equal(browserOwnedSecretUsable({ name: 'label', id: 'opaque-id', owned }), true);
  assert.equal(browserOwnedSecretUsable({ name: 'label', id: 'foreign-id', owned }), false);
  owned.__wbg_ptr = 0; // Simulate the generated by-value __destroy_into_raw transfer.
  assert.equal(browserOwnedSecretUsable({ name: 'label', id: 'opaque-id', owned }), false);
});


test('reconnect permits only captured initial offline error until fresh synchronization and exact terminal', async () => {
  const store = fakeStore(); store.isSynchronizing = false; store.syncError = 'offline';
  let settled = false;
  const result = waitForCanonicalTerminal({ passId: 'id', requestId: 'uuid', expectedStatus: 'Done', allowExistingSyncError: true, store }).then((value) => { settled = true; return value; });
  store.states = [{ secretId: 'id', requestId: 'uuid', clientStatus: 'Done' }]; store.emit();
  store.syncError = ''; store.emit(); await Promise.resolve(); assert.equal(settled, false);
  store.isSynchronizing = true; store.emit(); store.isSynchronizing = false; store.emit();
  assert.equal((await result).clientStatus, 'Done'); assert.equal(store.listeners.size, 0);
});

test('persistent captured offline error times out; new reconnect error and contradictory outcome fail', async () => {
  const store = fakeStore(); store.isSynchronizing = false; store.syncError = 'offline';
  await assert.rejects(waitForCanonicalTerminal({ passId: 'id', expectedStatus: 'Done', allowExistingSyncError: true, timeoutMs: 5, store }), /did not settle/);
  assert.equal(store.listeners.size, 0);
  const changed = waitForCanonicalTerminal({ passId: 'id', expectedStatus: 'Done', allowExistingSyncError: true, store });
  store.syncError = 'unexpected'; store.emit(); await assert.rejects(changed, /synchronization failed/);
  store.syncError = 'offline';
  const contradicted = waitForCanonicalTerminal({ passId: 'id', requestId: 'uuid', expectedStatus: 'Done', allowExistingSyncError: true, store });
  store.isSynchronizing = true; store.emit(); store.syncError = ''; store.isSynchronizing = false;
  store.states = [{ secretId: 'id', requestId: 'uuid', clientStatus: 'Declined' }]; store.emit();
  await assert.rejects(contradicted, /contradicts/);
});


test('same offline text recurring after clear is a new fatal error, never a blanket reconnect exemption', async () => {
  const store = fakeStore(); store.isSynchronizing = false; store.syncError = 'offline';
  const result = waitForCanonicalTerminal({ passId: 'id', expectedStatus: 'Done', allowExistingSyncError: true, store });
  store.isSynchronizing = true; store.syncError = ''; store.emit();
  store.isSynchronizing = false; store.syncError = 'offline'; store.emit();
  await assert.rejects(result, /synchronization failed/);
});
