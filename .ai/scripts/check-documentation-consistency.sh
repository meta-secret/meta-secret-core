#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
GLOSSARY="$ROOT_DIR/.ai/GLOSSARY.md"
CONSTRAINTS="$ROOT_DIR/.ai/CONSTRAINTS.md"

require_text() {
  local file="$1"
  local expected="$2"
  if ! grep -Fq -- "$expected" "$file"; then
    echo "Missing documentation text in ${file#$ROOT_DIR/}: $expected" >&2
    exit 1
  fi
}

require_text "$GLOSSARY" 'randomly generated by Core from the operating system CSPRNG'
require_text "$GLOSSARY" '**Encrypted Key Share**'
require_text "$CONSTRAINTS" 'Keep remote Encrypted Key Shares only as temporary outbound workflows'

# Approved product copy and the controlled fixture keep their exact wording.
# Bind exceptions to one physical full line at one path; copy drift is an error.
approved_hits=()
allow_approved_copy() {
  local relative="$1"
  local expected="$2"
  local file="$ROOT_DIR/$relative"
  local line count=0 number=0 match_number=0
  if [[ ! -f "$file" || ! -r "$file" ]]; then
    echo "Approved-copy guard: missing or unreadable $relative" >&2
    exit 1
  fi
  while IFS= read -r line || [[ -n "$line" ]]; do
    number=$((number + 1))
    if [[ "$line" == "$expected" ]]; then
      count=$((count + 1))
      match_number="$number"
    fi
  done < "$file"
  if [[ "$count" -ne 1 ]]; then
    echo "Approved-copy guard: $relative requires one exact full line; found $count" >&2
    exit 1
  fi
  approved_hits+=("$file:$match_number:$expected")
}

allow_approved_copy 'meta-secret/web-cli/ui/src/features/liveboard/controllerPresentation.ts' \
  "  shares: ['Each device stores an encrypted share.', 'Any 2 of 3 can recover the data. One share alone cannot.'],"
allow_approved_copy 'meta-secret/web-cli/ui/src/features/liveboard/controllerPresentation.ts' \
  "    ? ['Each device would store an encrypted share.', 'Any 2 of 3 could recover the data. One share alone cannot.']"
# Existing fixture-only value; it is not a prototype title.
allow_approved_copy 'meta-secret/web-cli/ui/tests/unit/liveboardFixtures.ts' \
  "  storageTitle: 'Encrypted shares',"

# Protocol terminology must use "Encrypted Key Share". Signed protocol
# envelopes remain valid terminology, so only the ambiguous encrypted forms
# are rejected here.
if matches="$(rg -n -i --with-filename --color never \
  --glob '*.md' --glob '*.rs' --glob '*.vue' --glob '*.ts' --glob '*.kt' \
  --glob '!**/.ai/artifacts/**' --glob '!**/target/**' --glob '!**/build/**' \
  'encrypted[[:space:]-]+(share|shares|envelope|envelopes)|зашифрованн[^[:space:]]*[[:space:]]+конверт' \
  "$ROOT_DIR/.ai" "$ROOT_DIR/docs" "$ROOT_DIR/meta-secret")"; then
  ambiguous=0
  while IFS= read -r hit; do
    approved=0
    for expected in "${approved_hits[@]}"; do
      if [[ "$hit" == "$expected" ]]; then
        approved=1
        break
      fi
    done
    if [[ "$approved" -eq 0 ]]; then
      printf '%s\n' "$hit"
      ambiguous=1
    fi
  done <<< "$matches"
  if [[ "$ambiguous" -ne 0 ]]; then
    echo 'Ambiguous encrypted-share/envelope terminology found; use Encrypted Key Share.' >&2
    exit 1
  fi
else
  status=$?
  if [[ "$status" -ne 1 ]]; then
    echo "Documentation terminology scan failed (rg status $status)." >&2
    exit "$status"
  fi
fi

# Master Key generation is random and independent of password KDFs.
if matches="$(rg -n -i --with-filename --color never \
  --glob '*.md' --glob '*.rs' --glob '*.vue' --glob '*.ts' --glob '*.kt' \
  --glob '!**/.ai/artifacts/**' --glob '!**/target/**' --glob '!**/build/**' \
  'Master[[:space:]]+Key[[:space:]]+(uses|is[[:space:]]+derived|derives[[:space:]]+from)|Master[[:space:]]+key[[:space:]]+derivation' \
  "$ROOT_DIR/.ai" "$ROOT_DIR/docs" "$ROOT_DIR/meta-secret")"; then
  printf '%s\n' "$matches"
  echo 'Stale password-derived Master Key documentation found.' >&2
  exit 1
else
  status=$?
  if [[ "$status" -ne 1 ]]; then
    echo "Master Key documentation scan failed (rg status $status)." >&2
    exit "$status"
  fi
fi

echo 'Core documentation terminology and Master Key lifecycle are consistent.'
