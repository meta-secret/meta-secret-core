#!/usr/bin/env python3
"""Finite controls of the real checker; all fixture writes stay in owned temp trees."""
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest


SCRIPT = Path(__file__).with_name("check-documentation-consistency.sh")
PRESENTATION = "meta-secret/web-cli/ui/src/features/liveboard/controllerPresentation.ts"
FIXTURE = "meta-secret/web-cli/ui/tests/unit/liveboardFixtures.ts"
APPROVED = (
    (PRESENTATION, "  shares: ['Each device stores an encrypted share.', 'Any 2 of 3 can recover the data. One share alone cannot.'],"),
    (PRESENTATION, "    ? ['Each device would store an encrypted share.', 'Any 2 of 3 could recover the data. One share alone cannot.']"),
    (FIXTURE, "  storageTitle: 'Encrypted shares',"),
)
RECEIPTS = []


def write(root, relative, text):
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def replace(root, relative, before, after):
    path = root / relative
    text = path.read_text(encoding="utf-8")
    assert text.count(before) == 1
    path.write_text(text.replace(before, after, 1), encoding="utf-8")


def run_checker(case, mutate=None, tool_error=False):
    with tempfile.TemporaryDirectory(prefix="metasecret-doc-check-") as directory:
        root = Path(directory)
        write(root, ".ai/GLOSSARY.md",
              "randomly generated by Core from the operating system CSPRNG\n**Encrypted Key Share**\n")
        write(root, ".ai/CONSTRAINTS.md",
              "Keep remote Encrypted Key Shares only as temporary outbound workflows\n")
        (root / "docs").mkdir()
        for relative in (PRESENTATION, FIXTURE):
            write(root, relative, "\n".join(line for path, line in APPROVED if path == relative) + "\n")
        copied = root / ".ai/scripts/check-documentation-consistency.sh"
        copied.parent.mkdir(parents=True)
        shutil.copyfile(SCRIPT, copied)
        if mutate:
            mutate(root)
        env = os.environ.copy()
        if tool_error:
            failing_rg = root / "owned-bin/rg"
            write(root, "owned-bin/rg", "#!/bin/sh\necho RG_TOOL_ERROR_CONTROL >&2\nexit 2\n")
            failing_rg.chmod(0o700)
            env["PATH"] = str(failing_rg.parent) + os.pathsep + env.get("PATH", "")
        result = subprocess.run(["/bin/bash", str(copied)], capture_output=True,
                                text=True, timeout=10, env=env, check=False)
        output = result.stdout + result.stderr
        RECEIPTS.append({"case": case, "exit": result.returncode, "output": output})
        return result.returncode, output


class DocumentationConsistencyTests(unittest.TestCase):
    def assert_offending_line(self, result, relative, line):
        code, output = result
        self.assertIn(f"{relative}:1:{line}", output, output)
        self.assertNotEqual(code, 0, output)

    def assert_copy_guard(self, result, relative):
        code, output = result
        self.assertNotEqual(code, 0, output)
        self.assertRegex(output.lower(), r"approved[ -]copy guard", output)
        self.assertIn(relative, output, output)

    def test_accepted_three_exact_presentation_lines_pass(self):
        code, output = run_checker("accepted-three-exact-lines")
        self.assertEqual(code, 0, output)
        self.assertIn("Core documentation terminology and Master Key lifecycle are consistent.", output)

    def test_technical_bad_terms_report_the_actual_offending_line(self):
        cases = (
            ("docs/bad-share.md", "Protocol encrypted share is ambiguous."),
            ("docs/bad-envelope.md", "Protocol encrypted-envelope is ambiguous."),
            ("docs/bad-russian.md", "зашифрованный конверт"),
            (PRESENTATION, "const rogue = 'encrypted share';"),
        )
        for relative, bad in cases:
            with self.subTest(path=relative):
                def mutate(root):
                    if relative == PRESENTATION:
                        path = root / relative
                        path.write_text(bad + "\n" + path.read_text(encoding="utf-8"), encoding="utf-8")
                    else:
                        write(root, relative, bad + "\n")
                self.assert_offending_line(run_checker("technical:" + relative, mutate), relative, bad)

    def test_approved_words_at_a_foreign_path_are_not_exempt(self):
        relative = "meta-secret/web-cli/ui/src/foreign.ts"
        line = APPROVED[0][1]
        result = run_checker("foreign-path", lambda root: write(root, relative, line + "\n"))
        self.assert_offending_line(result, relative, line)

    def test_changed_full_line_including_canonicalized_ui_rewrite_fails_guard(self):
        original = APPROVED[0][1]
        for changed in (original.replace("encrypted share", "Encrypted Key Share"), " " + original):
            with self.subTest(changed=changed):
                result = run_checker("changed-full-line", lambda root: replace(root, PRESENTATION, original, changed))
                self.assert_copy_guard(result, PRESENTATION)

    def test_missing_approved_line_or_file_fails_guard(self):
        cases = (
            (PRESENTATION, lambda root: replace(root, PRESENTATION, APPROVED[0][1] + "\n", "")),
            (FIXTURE, lambda root: (root / FIXTURE).unlink()),
        )
        for relative, mutate in cases:
            with self.subTest(path=relative):
                self.assert_copy_guard(run_checker("missing:" + relative, mutate), relative)

    def test_duplicate_or_appended_same_line_content_fails_guard(self):
        original = APPROVED[0][1]
        for changed in (original + "\n" + original, original + " // extra"):
            with self.subTest(changed=changed):
                result = run_checker("duplicate-or-appended", lambda root: replace(root, PRESENTATION, original, changed))
                self.assert_copy_guard(result, PRESENTATION)

    def test_stale_master_key_is_rejected_by_its_own_scan(self):
        relative = "docs/stale-master.md"
        bad = "Master Key is derived from a password."
        result = run_checker("stale-master-key", lambda root: write(root, relative, bad + "\n"))
        self.assert_offending_line(result, relative, bad)
        self.assertIn("Stale password-derived Master Key documentation found.", result[1])

    def test_rg_tool_error_cannot_be_reported_as_clean_success(self):
        code, output = run_checker("rg-error-status-2", tool_error=True)
        self.assertIn("RG_TOOL_ERROR_CONTROL", output, output)
        self.assertNotEqual(code, 0, output)


if __name__ == "__main__":
    suite = unittest.defaultTestLoader.loadTestsFromTestCase(DocumentationConsistencyTests)
    result = unittest.TextTestRunner(verbosity=2).run(suite)
    print("CHECKER_RECEIPTS=" + json.dumps(RECEIPTS, ensure_ascii=False))
    sys.exit(0 if result.wasSuccessful() else 1)
